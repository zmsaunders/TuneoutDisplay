# shellcheck shell=bash
# ─────────────────────────────────────────────────────────────────────────────
# lib/notes.sh — writes ~/smart-display-setup.md with this device's HA config.
# ─────────────────────────────────────────────────────────────────────────────

write_setup_notes() {
    local f="$CURRENT_HOME/smart-display-setup.md" host
    host="$(hostname)"
    {
        echo "# $DEVICE_NAME — Home Assistant setup"
        echo ""
        echo "Role: **$ROLE** · Audio: **$AUDIO_OUTPUT** · Host: \`$host.local\` · Device ID: \`$DEVICE_ID\`"
        echo ""
        echo "## MQTT entities (automatic)"
        echo ""
        echo "| Entity | Purpose |"
        echo "|---|---|"
        echo "| \`number.${DEVICE_ID}_brightness\` | Backlight 0–100 (0 = off) |"
        echo "| \`switch.${DEVICE_ID}_screen\` | Backlight power |"
        echo "| \`button.${DEVICE_ID}_reload_dashboard\` | Reload the kiosk page |"
        echo "| \`text.${DEVICE_ID}_dashboard_url\` | Send the kiosk to a URL (\`home\` = configured URL) |"
        if has_audio; then
            echo "| \`number.${DEVICE_ID}_speaker_volume\` | Master speaker volume |"
        fi
        if [ "$ROLE" = voice ]; then
            echo "| \`button.${DEVICE_ID}_start_listening\` | Push-to-talk |"
        fi
        echo ""
        echo "Entity IDs are generated by HA from the entity names — check the device page if they differ."
        echo ""
        if has_audio; then
            echo "## Voice / announcements (ESPHome)"
            echo ""
            echo "Settings → Devices & Services → Add Integration → ESPHome → host \`$host.local\`, port \`6053\`."
            if [ "$ROLE" = voice ]; then
                echo "Then **Set Up Voice Assistant** and pick a pipeline."
            else
                echo "Output-only: the device is a media player you can target with \`tts.speak\` / announcements."
            fi
            echo "LVA's media player has its own volume (TTS + LVA media); the MQTT Speaker Volume is the master."
            echo ""
        fi
        if [ "$MUSIC_ASSISTANT" = yes ]; then
            echo "## Music Assistant"
            echo ""
            echo "Player **$DEVICE_NAME** appears automatically in Music Assistant 2.7+ (sendspin)."
            echo ""
        fi
        echo "## Lovelace card"
        echo ""
        echo '```yaml'
        echo "type: custom:smart-display-card"
        echo "name: $DEVICE_NAME"
        echo "brightness_entity: number.${DEVICE_ID}_brightness"
        echo "screen_entity: switch.${DEVICE_ID}_screen"
        if has_audio; then
            echo "speaker_volume_entity: number.${DEVICE_ID}_speaker_volume"
            echo "media_player_entity: media_player.${DEVICE_ID}_media_player   # LVA (check the ID)"
        fi
        if [ "$ROLE" = voice ]; then
            echo "satellite_entity: assist_satellite.${DEVICE_ID}"
            echo "mute_entity: switch.${DEVICE_ID}_mute"
            echo "talk_entity: button.${DEVICE_ID}_start_listening"
        fi
        echo '```'
        echo ""
        echo "## Reload the dashboard after HA restarts"
        echo ""
        echo '```yaml'
        echo "automation:"
        echo "  - alias: \"Reload $DEVICE_NAME after HA restart\""
        echo "    triggers:"
        echo "      - trigger: homeassistant"
        echo "        event: start"
        echo "    actions:"
        echo "      - delay: \"00:00:30\""
        echo "      - action: button.press"
        echo "        target:"
        echo "          entity_id: button.${DEVICE_ID}_reload_dashboard"
        echo '```'
        echo ""
        echo "## Re-run / change settings"
        echo ""
        echo '```bash'
        echo "cd $SCRIPT_DIR && git pull && ./install.sh"
        echo '```'
    } > "$f"
    success "Wrote $f"
}
